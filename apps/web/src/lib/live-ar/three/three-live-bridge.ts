/**
 * Phase E — the generic bridge between Phase D's procedural 3D jewellery engine
 * (`@/lib/jewellery-3d-generator`) and the EXISTING Live AR camera pipeline. This is
 * the ONLY module in the whole runtime that is category/item-aware in the sense of
 * "which items currently have a 3D asset" -- and even that is a plain DATA lookup
 * (`GLTF_3D_ASSET_REGISTRY`), never a rendering/transform/attachment branch. Every
 * function below is generic over ANY `Gltf3dAssetMetadata`; nothing here contains
 * `if (jewelleryId === "diamond-choker")` or a choker-specific code path.
 *
 * WHY A REGISTRY, NOT A NEW DATABASE COLUMN: the catalogue schema has no 3D-asset
 * storage yet (confirmed by Phase A's direct schema audit, unchanged since --
 * `docs/jewellery-3d-asset-spec.md` §5 documents the target shape for whichever
 * milestone adds it). `resolveGltf3dAssetMetadata` is the SAME lookup a database
 * query would perform once that column exists -- swapping this in-memory map for a
 * real query later requires no change to any other function in this file, or to
 * `useLiveArSession.ts`'s call sites, which only ever call `resolveGltf3dAssetMetadata`/
 * `loadLive3dJewelleryAsset`, never read the registry directly.
 *
 * HOW THE EXISTING M6.8 3D FOUNDATION IS REUSED, UNCHANGED: `createThreeRenderer`/
 * `createThreeScene`/`addRestrainedLighting`/`applyEnvironmentLighting`/
 * `createThreeCamera`/`renderThreeFrame` (all from M6.8, all previously built but
 * never wired to a real call site) are called here exactly as designed, with zero
 * modification. `computeThreeJewelleryTransform` (three-transform.ts) is the ENTIRE
 * "coordinate mapping / scale-from-physical-dimensions / orientation" implementation
 * (Phase E Steps 8/9/10) -- this file adds no new geometry math, only the glue that
 * feeds it the EXISTING 2D pipeline's own already-smoothed, already-tracked output
 * (see `deriveScaleResultFromSmoothedTransform`'s doc comment below for exactly what
 * "reuse existing tracking smoothing" (Step 16) means here: this file introduces NO
 * new smoothing system at all -- it re-derives a `ScaleResult`/`RotationResult` shape
 * from the LiveTransform the EXISTING `TransformSmoother`/`TrackingStateMachine`
 * already produced this frame for the 2D sprite, so the 3D mesh inherits the exact
 * same smoothing characteristics for free).
 *
 * HONEST LIMITATION carried forward from M6.8 (three-types.ts's own file docstring):
 * the depth/perspective placement is DERIVED from the 2D pipeline's own validated
 * on-screen scale, not an independently calibrated 3D measurement -- there is no real
 * camera intrinsics or depth sensor anywhere in this pipeline. This file changes
 * nothing about that; it only finally exercises the math that was built to handle it.
 */
